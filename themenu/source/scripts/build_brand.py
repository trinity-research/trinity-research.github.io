"""Generate reproducible brand assets from one token source; never change content/ranking."""
import argparse
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def css_block(selector, values):
    declarations = ''.join(f'  --{key}: {value};\n' for key, value in values.items())
    return f'{selector} {{\n{declarations}}}\n'


def wordmark(palette, tokens, *, reversed_t=False):
    # All concepts share coordinates, type, letter spacing, and dimensions.
    # The experiment changes only the visual transform on the ordinary letter t.
    t_transform = ' transform="translate(8 0) scale(-1 1)"' if reversed_t else ''
    small_size = tokens['shared']['wordmark-the-size'].removesuffix('px')
    large_size = tokens['shared']['wordmark-size'].removesuffix('px')
    small_weight = tokens['shared']['wordmark-the-weight']
    small_font = escape(tokens['wordmark_small_font'], quote=True)
    large_font = escape(tokens['wordmark_font'], quote=True)
    menu_x = tokens['wordmark_menu_x']
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="176" height="52" viewBox="0 0 176 52" role="img" aria-labelledby="brand-name">
  <title id="brand-name">theMenu</title>
  <g fill="{palette['ink']}" aria-hidden="true">
    <g font-family="{small_font}" font-size="{small_size}" font-weight="{small_weight}" letter-spacing="-1">
      <text x="0" y="39"{t_transform}>t</text><text x="7" y="39">he</text>
    </g>
    <text x="{menu_x}" y="39" font-family="{large_font}" font-size="{large_size}" font-weight="900" letter-spacing="-2.3">MENU</text>
  </g>
  <rect x="{menu_x}" y="47" width="130" height="3" fill="{palette['signal']}"/>
</svg>
'''


def expected_files():
    tokens = json.loads((ROOT / 'brand/tokens.json').read_text(encoding='utf-8'))
    default = tokens['palettes'][tokens['default_palette']]
    values = {key: value for key, value in default.items() if key != 'label'}
    values.update(tokens['shared'])
    values.update({'font': tokens['font'], 'wordmark-font': tokens['wordmark_font'], 'wordmark-small-font': tokens['wordmark_small_font']})
    header = '/* Generated by scripts/build_brand.py from brand/tokens.json. */\n'
    files = {'assets/brand.css': header + css_block(':root', values)}
    concept_css = header
    for key, palette in tokens['palettes'].items():
        concept_css += css_block(f'[data-palette="{key}"]', {name: value for name, value in palette.items() if name != 'label'})
        files[f'docs/brand/assets/{key}-standard.svg'] = wordmark(palette, tokens)
    files['docs/brand/palettes.css'] = concept_css
    files['docs/brand/assets/utility-reversed-t.svg'] = wordmark(default, tokens, reversed_t=True)
    files['assets/wordmark.svg'] = wordmark(default, tokens)
    # Static HTML keeps a readable no-script fallback while shared brand copy
    # is regenerated from the same tokens as the visual assets.
    for name, expected_count in [('index.html', 1), ('docs/brand/index.html', 3)]:
        html = (ROOT / name).read_text(encoding='utf-8')
        for field in ['tagline', 'supporting_promise']:
            pattern = rf'(<(?P<tag>span|p)\b[^>]*data-brand-copy="{field}"[^>]*>)(.*?)(</(?P=tag)>)'
            html, count = re.subn(pattern, lambda match: match[1] + escape(tokens[field]) + match[4], html, flags=re.DOTALL)
            if count != expected_count:
                raise ValueError(f'{name}: expected {expected_count} {field} copy slots, found {count}')
        files[name] = html
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated assets differ from their source tokens')
    args = parser.parse_args()
    differences = []
    for name, content in expected_files().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                differences.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if differences:
        raise SystemExit('Regenerate brand assets with python scripts/build_brand.py: ' + ', '.join(differences))
    print('Brand assets match their source tokens.' if args.check else 'Generated default brand and isolated comparison assets.')


if __name__ == '__main__':
    main()
